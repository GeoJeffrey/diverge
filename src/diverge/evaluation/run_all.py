"""
run_all.py

One command to reproduce every number in reports/RESULTS.md.

    pip install -r requirements-eval.txt
    python -m diverge.evaluation.run_all              # everything (GPU recommended)
    python -m diverge.evaluation.run_all --quick      # CPU-friendly smoke run (smaller samples, no transformers)
    python -m diverge.evaluation.run_all --render     # only rebuild RESULTS.md from existing JSON

Steps
  1. coordination   bot-campaign detection benchmark (offline, ~5 min CPU)
  2. finetune       fine-tune FinBERT on finance tweets (skipped if models/finbert-tweets exists)
  3. sentiment      sentiment model benchmark on the held-out test split
  4. backtest       walk-forward predictive backtest on 1.7M tweets + Yahoo Finance prices
  5. outlook        train the dashboard's next-day outlook models + record their track record
  6. render         reports/RESULTS.md (API latency is added if reports/api_latency.json exists,
                    produced by scripts/bench_api.py against a running server)
"""

import argparse
import json
from pathlib import Path

REPORTS = Path("reports")


def _load(name):
    p = REPORTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _row(cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def render() -> Path:
    lines = ["# Diverge: evaluation results", "",
             "Generated by `python -m diverge.evaluation.run_all`. Every number below is read from the JSON",
             "files in this folder. Re-run the command to reproduce them.", ""]
    bullets = []

    sent = _load("sentiment_benchmark.json")
    if sent:
        lines += ["## 1. Sentiment model", "",
                  f"Held-out test set: `{sent['dataset']}` validation split ({sent['test_size']:,} finance tweets, "
                  f"trained on {sent['train_size']:,}).", "",
                  _row(["Model", "Accuracy", "Macro-F1", "F1 bearish", "F1 bullish", "F1 neutral", "Texts/sec"]),
                  _row(["---"] * 7)]
        for m in sent["models"]:
            f = m["f1_per_class"]
            lines.append(_row([m["model"], f"{m['accuracy']:.3f}", f"**{m['macro_f1']:.3f}**", f"{f['bearish']:.3f}",
                               f"{f['bullish']:.3f}", f"{f['neutral']:.3f}", f"{m['texts_per_sec']:,.0f}"]))
        lines.append("")
        by = {m["model"]: m for m in sent["models"]}
        best = max(sent["models"], key=lambda m: m["macro_f1"])
        base = sent["models"][0]
        bullets.append(
            f"Fine-tuned/benchmarked financial sentiment models on {sent['test_size']:,} held-out finance tweets; "
            f"best model ({best['model']}) reached {best['macro_f1']:.2f} macro-F1 vs {base['macro_f1']:.2f} "
            f"for the keyword baseline ({best['macro_f1'] / max(base['macro_f1'], 1e-9):.1f}x).")
        zs = next((m for k, m in by.items() if "zero-shot" in k), None)
        ft = next((m for k, m in by.items() if "fine-tuned" in k), None)
        if zs and ft:
            bullets.append(f"Domain-adapted FinBERT to social media text: macro-F1 {zs['macro_f1']:.2f} → "
                           f"{ft['macro_f1']:.2f} (+{100 * (ft['macro_f1'] - zs['macro_f1']):.0f} pts), "
                           f"{ft['texts_per_sec']:,.0f} texts/sec inference.")

    coord = _load("coordination_benchmark.json")
    if coord:
        h, ht, lr, gb = (coord[k] for k in ["heuristic_as_deployed", "heuristic_tuned", "logistic_regression", "gradient_boosting"])
        lines += ["## 2. Coordinated-campaign (bot) detection", "",
                  f"{coord['windows']:,} simulated 2-hour windows ({coord['posts']:,} posts), 50% with an injected campaign "
                  "(5-50% of traffic, paraphrased promo templates, scheduled posting with jitter). Negatives include "
                  "organic news bursts with shared headline text as hard negatives. 70/30 stratified split.", "",
                  _row(["Scorer", "ROC-AUC", "PR-AUC", "Precision", "Recall", "F1"]), _row(["---"] * 6)]
        for name, m in [("Original hand-weighted score (deployed threshold 40)", h),
                        ("Original score, threshold tuned on train", ht),
                        ("**Logistic regression (now used by the pipeline)**", lr),
                        ("Gradient-boosted trees (reference)", gb)]:
            lines.append(_row([name, f"{m['roc_auc']:.3f}", f"{m['pr_auc']:.3f}", f"{m['precision']:.3f}",
                               f"{m['recall']:.3f}", f"{m['f1']:.3f}"]))
        lines += ["", f"False-positive rate on organic news bursts: {100 * lr['fpr_on_news_bursts']:.1f}% "
                  "(the main remaining failure mode).", "",
                  "Recall by campaign size (share of window traffic):", "",
                  _row(["Bot share", "Windows", "Recall (learned)", "Recall (original)"]), _row(["---"] * 4)]
        for k, v in coord["recall_by_bot_share"].items():
            lines.append(_row([k, v["windows"], f"{v['recall_logreg']:.3f}", f"{v['recall_heuristic']:.3f}"]))
        lines += ["", "Ablation (ROC-AUC drop when a feature is removed): " +
                  ", ".join(f"{k} {v['auc_drop']:+.3f}" for k, v in coord["ablation"].items()), "",
                  "Near-duplicate search, exhaustive vs MinHash-LSH:", "",
                  _row(["Posts", "Exhaustive (s)", "LSH (s)", "Speed-up", "Pair recall"]), _row(["---"] * 5)]
        for r in coord["lsh_scaling"]:
            lines.append(_row([f"{r['posts']:,}", r["exact_seconds"], r["lsh_seconds"], f"{r['speedup']}x", r["pair_recall"]]))
        lines += ["", f"Integrity feature extraction throughput: {coord['feature_extraction_posts_per_sec']:,.0f} posts/sec (single CPU core).", ""]
        big = coord["lsh_scaling"][-1]
        bullets.append(
            f"Built a coordinated-posting (bot campaign) detector and a ground-truth benchmark of {coord['windows']:,} simulated "
            f"windows / {coord['posts'] / 1000:.0f}k posts; replaced a hand-tuned score (ROC-AUC {h['roc_auc']:.2f}, "
            f"{100 * h['recall']:.1f}% recall) with a learned scorer reaching ROC-AUC {lr['roc_auc']:.2f}, "
            f"F1 {lr['f1']:.2f} ({100 * lr['precision']:.0f}% precision / {100 * lr['recall']:.0f}% recall).")
        bullets.append(
            f"Implemented MinHash + LSH near-duplicate detection from scratch: {big['speedup']:.0f}x faster than "
            f"exhaustive search on {big['posts']:,} posts with {100 * big['pair_recall']:.0f}% pair recall.")

    bt = _load("backtest.json")
    if bt:
        p, v, d, ev = bt["panel"], bt["volatility"], bt["direction"], bt["attention_shock_event_study"]
        lines += ["## 3. Does narrative predict the next trading day?", "",
                  f"{p['posts']:,} posts → {p['ticker_days']:,} ticker-days ({', '.join(p['tickers'])}, "
                  f"{p['first_day']} to {p['last_day']}); source: {bt['source']}; sentiment model: {bt['sentiment_model']}. "
                  f"Expanding-window walk-forward by year; test years {v['linear']['test_years']}.", "",
                  "**Next-day volatility (|return|)**: price-only HAR baseline vs. baseline + narrative features", "",
                  _row(["Model", "OOS R² price-only", "OOS R² + narrative", "MSE reduction", "Rank IC (price → +narr.)", "Diebold-Mariano p"]),
                  _row(["---"] * 6)]
        for k, m in v.items():
            lines.append(_row([k, f"{m['oos_r2_price_only']:.3f}", f"{m['oos_r2_with_narrative']:.3f}",
                               f"{m['mse_reduction_pct']:+.1f}%", f"{m['rank_ic_price_only']:.3f} → {m['rank_ic_with_narrative']:.3f}",
                               f"{m['dm_p_value']:.4f}"]))
        lines += ["", "**Next-day excess return direction** (vs the market index)", "",
                  _row(["Model", "AUC price-only", "AUC + narrative", "Long/short Sharpe after 5bp costs (price → +narr.)"]),
                  _row(["---"] * 4)]
        for k, m in d.items():
            lines.append(_row([k, f"{m['price_only']['auc']:.3f}", f"{m['with_narrative']['auc']:.3f}",
                               f"{m['price_only']['long_short_sharpe_after_costs']:.2f} → {m['with_narrative']['long_short_sharpe_after_costs']:.2f}"]))
        lines += ["", f"**Event study:** on top-decile attention-shock days ({ev['shock_days']:,}), next-day |return| averaged "
                  f"{ev['mean_next_day_abs_return_shock_pct']:.2f}% vs {ev['mean_next_day_abs_return_other_pct']:.2f}% otherwise: "
                  f"**{ev['volatility_ratio']:.2f}x** (bootstrap 95% CI {ev['ratio_95ci'][0]:.2f}-{ev['ratio_95ci'][1]:.2f}).", "",
                  "Permutation importance (% MSE increase when shuffled, last test year): " +
                  ", ".join(f"{k} {val:.2f}" for k, val in list(bt["permutation_importance_pct_mse"].items())[:8]), ""]
        best = max(v.values(), key=lambda m: m["mse_reduction_pct"])
        if best["mse_reduction_pct"] > 0 and best["dm_p_value"] < 0.05:
            bullets.append(
                f"Showed social-media narrative features add out-of-sample information beyond prices: next-day volatility "
                f"forecast error reduced {best['mse_reduction_pct']:.1f}% vs a HAR baseline (Diebold-Mariano {'p<0.001' if best['dm_p_value'] < 0.001 else 'p=' + format(best['dm_p_value'], '.3f')}) "
                f"in a walk-forward backtest over {p['ticker_days']:,} ticker-days / {p['posts'] / 1e6:.1f}M posts.")
        else:
            bullets.append(
                f"Ran a leakage-checked walk-forward backtest over {p['ticker_days']:,} ticker-days / {p['posts'] / 1e6:.1f}M posts; "
                f"narrative features did not significantly beat a price-only volatility baseline (MSE {best['mse_reduction_pct']:+.1f}%). "
                "This is reported as a negative result.")
        lo = ev["ratio_95ci"][0]
        if lo > 1:
            bullets.append(f"Found next-day volatility is {ev['volatility_ratio']:.1f}x higher after social-attention shocks "
                           f"(95% CI {lo:.2f}-{ev['ratio_95ci'][1]:.2f}).")
        lines += ["Direction (return sign) results near AUC 0.5 are expected for liquid large caps; we do not claim tradeable alpha.", ""]

    ol = _load("outlook_track_record.json")
    if ol:
        t = ol["track_record"]; d, mv = t["direction"], t["move"]
        lc, big = d["lean_calls"], mv["larger_than_usual_calls"]
        lines += ["## 4. Next-day outlook (served by the dashboard)", "",
                  f"Walk-forward test {t['test_period']} ({t['test_days']:,} ticker-days). Linear models, refit on all data for serving.", "",
                  _row(["Metric", "Value"]), _row(["---"] * 2),
                  _row(["Direction accuracy, all days", f"{100 * d['accuracy']:.1f}% (always-up: {100 * d['always_up_accuracy']:.1f}%)"]),
                  _row(["Direction ROC-AUC / Brier", f"{d['auc']:.3f} / {d['brier']:.4f}"]),
                  _row(["Accuracy of 'leans up/down' calls", f"{100 * (lc['accuracy'] or 0):.1f}% on {100 * lc['share_of_days']:.0f}% of days"]),
                  _row(["Move size OOS R² (price-only → with social)", f"{mv['oos_r2_price_only']:.3f} → {mv['oos_r2']:.3f}"]),
                  _row(["'Bigger move than usual' precision", f"{100 * (big['precision'] or 0):.1f}% vs base rate {100 * big['base_rate']:.1f}%"]),
                  ""]
        if big["precision"] and big["precision"] > big["base_rate"]:
            bullets.append(
                f"Shipped an explainable next-day outlook (direction + expected move) with a public track record: "
                f"'bigger move than usual' calls were right {100 * big['precision']:.0f}% of the time vs a "
                f"{100 * big['base_rate']:.0f}% base rate over {t['test_days']:,} out-of-sample ticker-days.")

    api = _load("api_latency.json")
    if api:
        lines += ["## 5. API performance", "",
                  f"{api['requests_per_endpoint']:,} requests per endpoint at concurrency {api['concurrency']} "
                  f"({api.get('environment', {}).get('os', '')} laptop, single uvicorn worker).", "",
                  _row(["Endpoint", "p50 ms", "p95 ms", "p99 ms", "Throughput (req/s)", "Errors"]), _row(["---"] * 6)]
        for k, m in api["endpoints"].items():
            lines.append(_row([k, m["p50_ms"], m["p95_ms"], m["p99_ms"], m["throughput_rps"], f"{100 * m['error_rate']:.1f}%"]))
        lines.append("")
        e = list(api["endpoints"].values())
        bullets.append(f"Served analytics through a JWT-secured FastAPI + PostgreSQL backend at p95 ≤ "
                       f"{max(x['p95_ms'] for x in e):.0f} ms and {min(x['throughput_rps'] for x in e):.0f}+ req/s "
                       f"under {api['concurrency']} concurrent clients.")

    lines += ["## Resume bullets generated from these results", "",
              "Each bullet uses only the numbers above. Pick 3-4 and lead with the strongest.", ""]
    lines += [f"- {b}" for b in bullets] + [""]
    out = REPORTS / "RESULTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--skip", nargs="*", default=[],
                    choices=["coordination", "finetune", "sentiment", "backtest", "outlook"])
    a = ap.parse_args()

    if not a.render:
        if "coordination" not in a.skip:
            from . import coordination_benchmark

            print("[1/5] coordination benchmark ...")
            coordination_benchmark.run(1000 if a.quick else 4000, out_dir=REPORTS, export_weights=not a.quick)
        if "finetune" not in a.skip and not a.quick:
            from .sentiment_benchmark import FINETUNED_DIR

            if not FINETUNED_DIR.exists():
                from . import finetune_sentiment

                print("[2/5] fine-tuning FinBERT ...")
                finetune_sentiment.main()
        if "sentiment" not in a.skip:
            from . import sentiment_benchmark

            print("[3/5] sentiment benchmark ...")
            sentiment_benchmark.run(REPORTS, skip_transformers=a.quick)
        if "backtest" not in a.skip:
            from . import backtest

            print("[4/5] backtest ...")
            backtest.main("tweets", "tfidf" if a.quick else "auto", 200_000 if a.quick else None,
                          with_duplicates=not a.quick, out_dir=REPORTS)
        if "outlook" not in a.skip:
            from . import train_outlook

            print("[5/5] training the next-day outlook ...")
            train_outlook.main("tfidf" if a.quick else "auto", 200_000 if a.quick else None, REPORTS)
    print(f"Wrote {render()}")


if __name__ == "__main__":
    main()
